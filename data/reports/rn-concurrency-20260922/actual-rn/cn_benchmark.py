def main():
    flags = sys.argv[1:]
    state_args = [value for value in flags if value.startswith("--state-file=")]
    if "--state-file" in flags:
        state_args.append(flags[flags.index("--state-file") + 1])
    if not state_args and not any(value in flags for value in ("-h", "--help")):
        raise SystemExit("Provide --state-file cn_query_cursor.json for this Chinese workload")
    if state_args:
        state_path = pathlib.Path(state_args[0].removeprefix("--state-file=")).resolve()
        if state_path == pathlib.Path(__file__).with_name("query_cursor.json").resolve():
            raise SystemExit("Do not reuse the English query_cursor.json")
    api.query_for = lambda index: QUERIES[index]
    api.QUERY_COUNT = len(QUERIES)
    api.__doc__ = __doc__
    return api.main()


if __name__ == "__main__":
    raise SystemExit(main())
